"""Export trained weights for the browser (works from file://): ai/model.js with int8-quantised layers.
usage: python3 tools/ai/export_browser.py <checkpoint.pt> [out=ai/model.js]"""
import base64, json, os, sys, numpy as np, torch
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from model import Net, LAYERS
ck, out = sys.argv[1], (sys.argv[2] if len(sys.argv) > 2 else 'ai/model.js')
net = Net(); net.load_state_dict(torch.load(ck)['net'])
layers = {}
for name in LAYERS:
    L = getattr(net, name); w = L.weight.detach().numpy().astype(np.float32); b = L.bias.detach().numpy().astype(np.float32)
    scale = np.abs(w).max(1, keepdims=True) / 127 + 1e-12                       # per output row
    q = np.clip(np.round(w / scale), -127, 127).astype(np.int8)
    layers[name] = {'shape': list(w.shape), 'q': base64.b64encode(q.tobytes()).decode(), 'scale': base64.b64encode(scale.astype(np.float32).ravel().tobytes()).decode(),
                    'b': base64.b64encode(b.tobytes()).decode()}
os.makedirs(os.path.dirname(out) or '.', exist_ok=True)
with open(out, 'w') as f:
    f.write('// Trained Clash Royale policy (PPO self-play). Generated by tools/ai/export_browser.py — do not edit.\n')
    f.write('window.NN_MODEL = ' + json.dumps({'layers': layers, 'source': os.path.basename(os.path.dirname(ck))}) + ';\n')
print(out, os.path.getsize(out) // 1024, 'KB')
